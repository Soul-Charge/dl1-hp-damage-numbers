static HMODULE g_realWinmm = nullptr;

void WinmmProxyInit() {
    if (g_realWinmm) return;
    wchar_t sysDir[MAX_PATH] = {};
    UINT len = GetSystemDirectoryW(sysDir, MAX_PATH);
    if (len == 0 || len + 12 >= MAX_PATH) return;
    wcscat_s(sysDir, L"\\winmm.dll");
    g_realWinmm = LoadLibraryW(sysDir);
    if (!g_realWinmm) return;
    for (size_t i = 0; i < sizeof(kExportNames) / sizeof(kExportNames[0]); ++i) {
        g_winmmProcs[i] = GetProcAddress(g_realWinmm, kExportNames[i]);
    }
}
